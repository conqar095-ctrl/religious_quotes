def search_database(topic_hint: str, ref_type: str = None) -> dict:
    """
    يبحث في قاعدة البيانات عن أقرب نص ديني للموضوع المطلوب.
    يرجع dict فيه: type, source, text
    أو None لو مفيش نتيجة.
    """
    topic_hint_lower = topic_hint.lower()
    words = [w for w in topic_hint_lower.split() if len(w) > 2]

    best_match = None
    best_score = 0

    for entry in RELIGIOUS_DATABASE:
        if ref_type and ref_type.upper() != entry["type"]:
            continue

        score = 0

        for keyword in entry["keywords"]:
            if keyword in topic_hint_lower:
                score += 4
            for word in words:
                if word in keyword or keyword in word:
                    score += 1

        topic_lower = entry["topic"].lower()
        for word in words:
            if word in topic_lower:
                score += 3

        if score > best_score:
            best_score = score
            best_match = entry

    if best_score >= 2:
        return best_match

    return None
